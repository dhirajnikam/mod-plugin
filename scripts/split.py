#!/usr/bin/env python3
"""Builds the plugins split from Cockpit: cockpit-core and its add-ons, in plugins/, from the one source in cockpit/.

Run from anywhere after changing cockpit/: python3 scripts/split.py. With --check it writes nothing and exits 1,
naming the files that differ, when plugins/ (or cockpit/hooks/acts.ts) is out of date.

A plugin cannot import a file outside its own folder, so each split plugin holds copies of the files it needs:
- cockpit-core: every event hook, the state, the actions, the experts and the pane's header and tabs. It owns the
  state, and answers $.cockpit.set and $.cockpit.act, through which the add-ons change it.
- an add-on per tab (overview, activity, agents, git, rules): that tab's view, drawn below core's header.
- cockpit-chat: the band above the prompt, the spinner's words and the chat's cards and rows.
An add-on reads core's state as it is, and its actions run in core: its actions.ts sends each one there by name.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "cockpit"
OUT = ROOT / "plugins"
CORE = "cockpit-core"
# Each add-on: its tab, the component that draws it, the tab's file, what it adds
TABS = [
    ("overview", "overview", "Overview", "overview", "the task's progress ring and steps, checks, the agents as a neural view, changed files, context, and the judges' decisions"),
    ("activity", "files", "Files", "activity", "a live feed of every file read, edited or searched, the codebase's features as a map, and the impact of a change"),
    ("agents", "agents", "Agents", "agents", "the Build, Verify and Review pipelines, the six experts, agents you describe, their trackers and two testers on every change"),
    ("git", "git", "Git", "git", "the next commit written from the diff, commit modes from manual to automatic, accounts, and a git graph of every branch"),
    ("rules", "rules", "Rules", "rules", "the hooks, permission rules and CLAUDE.md instructions of the repository or of you, to add, edit and delete"),
]
# Run in the add-on itself: they take a function (the work, a change to a file) that cannot be sent to core as data.
# Their writes to the state go to core all the same, through set
LOCAL = {"set", "toast", "inBackground", "writeSettings", "writeInstructions", "loadRules"}
# Called by the local ones above, so sent to core too
ALSO_REMOTE = {"claim", "release"}
HEAD = "// Generated by scripts/split.py from cockpit/: edit there and run it again\n"


def read(rel: str) -> str:
    return (SRC / rel).read_text(encoding="utf-8")


def async_functions():
    """Every async function the actions export, with how many arguments it takes after $."""
    found = {}
    for f in sorted((SRC / "hooks/ops").glob("*.ts")):
        text = f.read_text(encoding="utf-8")
        for m in re.finditer(r"^export async function (\w+)\(", text, re.M):
            depth, i, start = 1, m.end(), m.end()
            while depth:
                depth += {"(": 1, ")": -1}.get(text[i], 0)
                i += 1
            params, depth, n, cur = text[start : i - 1], 0, 0, ""
            for ch in params:
                depth += {"(": 1, "{": 1, "[": 1, "<": 1, ")": -1, "}": -1, "]": -1, ">": -1}.get(ch, 0)
                if ch == "," and depth == 0:
                    n, cur = n + 1, ""
                else:
                    cur += ch
            found[m.group(1)] = (f.stem, n + (1 if cur.strip() else 0) - 1)
    return found


def view_imports():
    """The actions the views and drawings import, by name."""
    names = set()
    for f in [*sorted((SRC / "hooks/tabs").glob("*.tsx")), SRC / "hooks/drawings.tsx", SRC / "hooks/pane.tsx"]:
        for block in re.findall(r"import \{([^}]*)\} from '\.\.?/actions'", f.read_text(encoding="utf-8")):
            names |= {n.strip().split(" as ")[0] for n in block.split(",") if n.strip()}
    return names


def remote():
    fns = async_functions()
    return {n: fns[n] for n in sorted((view_imports() & set(fns)) - LOCAL | ALSO_REMOTE)}


def acts_ts(rem) -> str:
    calls = "\n".join(f"    case '{n}':\n      return {n}(${''.join(f', {a}' for a in 'abcd'[:k])})" for n, (_, k) in rem.items())
    imports = ", ".join(rem)
    return f"""{HEAD}// What $.cockpit.act runs, by name: the actions the pane's views and the chat's drawings call, which the plugins
// split from Cockpit send here to run where the state is written
import type {{ $ }} from './ops/core'
import {{ {imports} }} from './actions'

export const ACTS = {json.dumps(list(rem))} as const

export async function act($: $, name: string, args: unknown[]): Promise<unknown> {{
  const [a, b, c, d] = args as [never, never, never, never]
  switch (name) {{
{calls}
  }}
  return undefined
}}
"""


def rename(text: str) -> str:
    """The copies are cockpit-core's: its state, its agents (cockpit-core:prover) and what it provides."""
    text = text.replace("plugin: 'cockpit', key", f"plugin: '{CORE}', key")
    text = re.sub(r"\bcockpit:(?=[a-z$])", f"{CORE}:", text)
    text = text.replace("a.provider !== 'cockpit'", f"a.provider !== '{CORE}'")
    return text.replace("    cockpit: { s: Shaped<Ph> }", f"    '{CORE}': {{ s: Shaped<Ph> }}")


def replace_fn(text: str, name: str, body: str) -> str:
    m = re.search(rf"^export (async )?function {name}\(.*?^\}}\n", text, re.M | re.S)
    assert m, name
    return text[: m.start()] + body + text[m.end() :]


def addon_core_ts() -> str:
    """ops/core.ts for an add-on: its writes go to core, which owns the state."""
    text = rename(read("hooks/ops/core.ts"))
    text = replace_fn(text, "set", """// Split from Cockpit, the state is cockpit-core's and only it writes it: a change goes there as data, a function of
// the state applied to the state as it stands
export async function set($: $, patch: Patch) {
  await $.cockpit.set({ patch: typeof patch === 'function' ? patch(await read($, S)) : patch })
}
""")
    text = replace_fn(text, "claim", """export async function claim($: $, kind: string, label: string) {
  return (await $.cockpit.act({ name: 'claim', args: [kind, label] })) === true
}
""")
    # Preferences are core's to load, at its session start
    text = replace_fn(text, "loadPrefs", """export async function loadPrefs() {}
""")
    return replace_fn(text, "release", """export async function release($: $, kind: string) {
  await $.cockpit.act({ name: 'release', args: [kind] }).catch(() => null)
}
""")


def addon_actions_ts(rem) -> str:
    """actions.ts for an add-on: every action the views call is sent to core by name, the rest are the copies."""
    files = sorted({f for f, _ in rem.values()})
    types = "\n".join(f"import type * as {f.replace('-', '_')} from './ops/{f}'" for f in files)
    stubs = "\n".join(f"export function {n}($: $, ...args: unknown[]): ReturnType<typeof {f.replace('-', '_')}.{n}> {{\n  return $.cockpit.act({{ name: '{n}', args }}) as never\n}}" for n, (f, _) in rem.items() if n not in ALSO_REMOTE)
    return f"""{HEAD}// The actions of an add-on split from Cockpit: those the views call run in cockpit-core, which owns the state, sent
// there by name; the rest (helpers, and the few that take a function) are the copies beside this file
{read('hooks/actions.ts').split(chr(10), 1)[1]}import type {{ $ }} from './ops/core'
{types}

{stubs}
"""


def manifest(name: str, description: str, deps: list[str], types: bool) -> str:
    base = json.loads(read(".claude-plugin/plugin.json"))
    m = {"name": name, "version": base["version"], "description": description}
    if types:
        m["types"] = "./types/index.d.ts"
    if deps:
        m["dependencies"] = deps
    for k in ("author", "homepage", "repository", "license"):
        m[k] = base[k]
    return json.dumps(m, indent=2) + "\n"


def readme(name: str, what: str, needs_core: bool) -> str:
    install = f"/plugin install {CORE} --marketplace dhirajnikam/mod-plugin\n" if needs_core else ""
    return f"""# {name}

{what}

Part of [Cockpit](../../README.md), split so you can install only the parts you want.{' It needs `cockpit-core`, which holds the state and the events, and draws into its pane.' if needs_core else ''} Install it at the prompt of a Claude Code session:

```
{install}/plugin install {name} --marketplace dhirajnikam/mod-plugin
```

Install the parts or the all-in-one `cockpit`, not both. This folder is generated by `scripts/split.py` from
`cockpit/`: change the code there.
"""


def core_register() -> str:
    text = rename(read("hooks/register.tsx"))
    text = text.replace("import { drawings } from './drawings'\nimport { fullPane } from './full-pane'\n", "import { paneFrame } from './pane'\n")
    text = text.replace("  // The band, spinner and chat cards (drawings.tsx), and the pane (full-pane.tsx)\n  drawings(on)\n  fullPane(on, () => root)",
                        "  // The pane's header and tabs; each add-on draws its tab's view below them\n  paneFrame(on, () => root)")
    assert "drawings" not in text and "fullPane" not in text and "paneFrame(on" in text
    return HEAD + text


def addon_register(tab: str, comp: str, file: str) -> str:
    return f"""{HEAD}import type {{ Register }} from 'claude-code'
import {{ PANE }} from './state'
import {{ paneV, piece }} from './pane'
import {{ {comp} }} from './tabs/{file}'

// One tab of Cockpit's pane, drawn below cockpit-core's header and tabs, which show it once this says it is here
export const register: Register = on => {{
  let root = ''
  on('session.start', async ($, e, next) => {{
    const r = await next(e)
    root = await $.session.cwd().catch(() => '')
    await $.cockpit.tab({{ id: '{tab}' }}).catch(() => null)
    return r
  }})
  on('ui.render', {{ component: 'Pane', requestId: PANE }}, async ($, e, next) => {{
    const v = await paneV($, e, root)
    if (!v || v.s.tab !== '{tab}') return next(e)
    const below = await next(e)
    return (
      <v.ui.Box flexDirection="column">
        {{below}}
        {{piece(v, {comp}($, v))}}
      </v.ui.Box>
    )
  }})
}}
"""


