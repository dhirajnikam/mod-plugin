# state where core does and records what the add-on asks of it
STAND_IN = """  on('engine.create', async (_$, e, next) => ({ ...(await next(e)), cockpit: { set: async () => true, act: async () => null, tab: async () => true } }))
  // Core keeps the state under its atom's shape tag: { shape, value }
  // A change is written, then handed on to the test's hook beneath, which records it; so are the actions
  on('cockpit.set', async ($, e, next) => {
    const { value } = await $.state.get({ plugin: 'cockpit-core', key: 's' })
    await $.state.set({ plugin: 'cockpit-core', key: 's' }, { shape: 'ph-23', value: { ...(value?.value as object), ...(e.patch as object) } } as never)
    return next(e)
  })
  // The test's way to lay the state, which only its owner writes
  on('tool.call', { tool: 'Seed' as never }, async ($, e) => {
    await $.state.set({ plugin: 'cockpit-core', key: 's' }, { shape: 'ph-23', value: (e as unknown as { state: never }).state } as never)
    return { result: 'ok' }
  })"""


