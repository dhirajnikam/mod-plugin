def plugins():
    """Every generated file, by its path under the repository."""
    rem = remote()
    files: dict[str, str] = {"cockpit/hooks/acts.ts": acts_ts(rem)}
    shared = ["hooks/state.ts", "hooks/theme.ts", "hooks/logic.ts", "hooks/memory.ts", "hooks/rules.ts", "hooks/pane.tsx",
              "hooks/tabs/shared.tsx", "hooks/tabs/header.tsx", "types/index.d.ts", "tsconfig.json", "hooks/hooks.json"]
    ops = [f"hooks/ops/{f.name}" for f in sorted((SRC / "hooks/ops").glob("*.ts"))]

    def put(plugin: str, rel: str, text: str):
        files[f"plugins/{plugin}/{rel}"] = text

    # cockpit-core: the source, less the tab views and the chat's drawings
    for rel in [*shared, *ops, "hooks/actions.ts", "hooks/acts.ts"]:
        put(CORE, rel, files["cockpit/hooks/acts.ts"] if rel == "hooks/acts.ts" else rename(read(rel)))
    put(CORE, "hooks/register.tsx", core_register())
    put(CORE, "hooks/views.tsx", HEAD + "export * from './tabs/shared'\nexport * from './tabs/header'\n")
    put(CORE, "hooks/state.ts", rename(read("hooks/state.ts")).replace("  tab: 'overview',\n", "  tab: 'overview',\n  // No tab until an add-on says it is here\n  tabsAvailable: [],\n", 1))
    for f in sorted((SRC / "agents").glob("*.md")):
        put(CORE, f"agents/{f.name}", rename(f.read_text(encoding="utf-8")))
    put(CORE, ".claude-plugin/plugin.json", manifest(CORE, "Cockpit's core: the state, the events, the experts, /cockpit and the pane's header; add the tabs you want as cockpit-overview, -activity, -agents, -git and -rules, and the chat's band and cards as cockpit-chat", [], True))
    put(CORE, "tests/core.test.tsx", CORE_TEST)
    put(CORE, "README.md", readme(CORE, "Cockpit's core: what every part reads. It follows the session (prompts, tool calls, turns, agents, the judges), keeps the state, registers the six experts and `/cockpit`, and draws the pane's header and tabs. Add the tabs you want as add-ons.", False))

    def addon(name: str, what: str, register: str, extra: list[str]):
        for rel in [*shared, *ops, *extra]:
            put(name, rel, rename(read(rel)))
        put(name, "hooks/ops/core.ts", addon_core_ts())
        put(name, "hooks/actions.ts", addon_actions_ts(rem))
        put(name, "hooks/register.tsx", register)
        put(name, ".claude-plugin/plugin.json", manifest(name, what, [CORE], False))
        put(name, "README.md", readme(name, what[0].upper() + what[1:] + ".", True))

    for short, tab, comp, file, what in TABS:
        name = f"cockpit-{short}"
        addon(name, f"Cockpit's {comp if short != 'activity' else 'Activity'} tab: {what}", addon_register(tab, comp, file), [f"hooks/tabs/{file}.tsx"])
        put(name, "hooks/views.tsx", HEAD + f"export * from './tabs/shared'\nexport * from './tabs/header'\nexport * from './tabs/{file}'\n")
        put(name, "tests/tab.test.tsx", addon_test(tab, "git" if tab == "overview" else "overview").replace("{name}", name))
    addon("cockpit-chat", "Cockpit around the chat: the band above the prompt with progress and context, the spinner's words, tool calls as cards, and the line under the prompt", CHAT_REGISTER, ["hooks/drawings.tsx"])
    put("cockpit-chat", "tests/chat.test.tsx", CHAT_TEST)
    put("cockpit-chat", "hooks/views.tsx", HEAD + "export * from './tabs/shared'\nexport * from './tabs/header'\n")
    return files


def main():
    check = "--check" in sys.argv
    want = plugins()
    have = {str(p.relative_to(ROOT)) for p in OUT.rglob("*") if p.is_file() and ".claude-plugin/types" not in str(p)} if OUT.exists() else set()
    stale = sorted(rel for rel, text in want.items() if not (ROOT / rel).exists() or (ROOT / rel).read_text(encoding="utf-8") != text)
    extra = sorted(have - set(want))
    if check:
        for rel in stale + extra:
            print(f"out of date: {rel}")
        if stale or extra:
            print("Run python3 scripts/split.py and commit what it writes.")
        sys.exit(1 if stale or extra else 0)
    for rel in stale:
        (ROOT / rel).parent.mkdir(parents=True, exist_ok=True)
        (ROOT / rel).write_text(want[rel], encoding="utf-8")
    for rel in extra:
        (ROOT / rel).unlink()
    print(f"{len(stale)} written, {len(extra)} removed, {len(want)} in all")


if __name__ == "__main__":
    main()
